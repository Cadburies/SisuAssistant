#!/usr/bin/env python3
"""Draw a first-draft KiCad 10 schematic from a Python net table, then check it.

    python3 -I MarineBoard/kicad-skills/scripts/draft_sch.py <project.kicad_pro> <table.py>

The table defines PARTS, NOTES, PAPER and TITLE (see daughter-fridge/draft_nets.py).
Symbols come from KiCad's bundled libraries, flattened into the schematic. Every pin
gets a 2.54 mm wire stub and a net label, so the drawing is correct before it is pretty.

Then, with kicad-cli: ERC (any violation fails), netlist export, a pin-by-pin compare
against the table (wrong net, unexpected pin, one-pin net all fail), and a PDF in
<project dir>/docs/<name>-schematic.pdf. Exit 0 only when all of that passes.

Overwrites <name>.kicad_sch. Use it for the first draft only: once someone edits the
schematic by hand, the .kicad_sch is the source and the table is retired.
"""
import json, os, runpy, subprocess, sys, tempfile, uuid
from pathlib import Path
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kicad_libpins as libpins  # noqa: E402
from kicad_sym import refuse_write  # noqa: E402  same guards as the symbol script

MARKER = "Generated by draft_sch.py"

KICAD_CLI = os.environ.get("KICAD_CLI", "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli")
STUB = 2.54
# lib pin angle -> (outward step on the sheet, label angle, label justify)
ANG = {0: ((-1, 0), 180, "right bottom"), 180: ((1, 0), 0, "left bottom"),
       90: ((0, 1), 270, "right bottom"), 270: ((0, -1), 90, "left bottom")}


def u():
    return str(uuid.uuid4())


def eff(hide=False, justify=None, size=1.27):
    j = f" (justify {justify})" if justify else ""
    return f"(effects (font (size {size} {size})){j})" + (" (hide yes)" if hide else "")


def prop(name, value, x, y, hide=False, justify=None):
    return f'(property "{name}" "{value}" (at {x:.2f} {y:.2f} 0) {eff(hide, justify)})'


def build(t, project, root):
    title = dict(t["TITLE"], **{"comment 3": MARKER})
    tb = " ".join(f'({k} "{v}")' if not k.startswith("comment") else f'(comment {k.split()[1]} "{v}")'
                  for k, v in title.items())
    out = ['(kicad_sch (version 20260306) (generator "eeschema") (generator_version "10.0")',
           f'(uuid "{root}")', f'(paper "{t.get("PAPER", "A3")}")', f"(title_block {tb})", "(lib_symbols"]
    for lid in sorted({p[1] for p in t["PARTS"]}):
        out.append(libpins.flat(*lid.split(":")))
    out.append(")")
    for ref, lid, val, fp, (sx, sy), nets, *_ in t["PARTS"]:
        power, used = ref.startswith("#"), set()
        for unit, pins in libpins.pins(*lid.split(":")).items():
            ux = sx + (30.48 if unit > 1 else 0)
            vertical2 = len(pins) == 2 and all(a in (90, 270) for *_, a, _ in pins)
            ref_at = (ux + 2.54, sy - 1.27) if vertical2 else (ux, sy - 10.16)
            val_at = (ux + 2.54, sy + 1.27) if vertical2 else (ux, sy + 10.16)
            just = "left" if vertical2 else None
            pin_uuids = " ".join(f'(pin "{n}" (uuid "{u()}"))' for n, *_ in pins)
            out.append(
                f'(symbol (lib_id "{lid}") (at {ux:.2f} {sy:.2f} 0) (unit {unit}) (exclude_from_sim no)'
                f' (in_bom {"no" if power else "yes"}) (on_board {"no" if power else "yes"}) (dnp no) (uuid "{u()}")'
                f' {prop("Reference", ref, *ref_at, hide=power, justify=just)}'
                f' {prop("Value", val, *val_at, justify=just)}'
                f' {prop("Footprint", fp, ux, sy, hide=True)} {prop("Datasheet", "", ux, sy, hide=True)}'
                f' {pin_uuids} (instances (project "{project}" (path "/{root}" (reference "{ref}") (unit {unit})))))')
            for n, _name, px, py, a, _type in pins:
                if n not in nets:
                    sys.exit(f"{ref} pin {n} has no net in the table")
                used.add(n)
                x, y = ux + px, sy - py
                if nets[n] is None:
                    out.append(f'(no_connect (at {x:.2f} {y:.2f}) (uuid "{u()}"))')
                    continue
                (dx, dy), la, lj = ANG[a]
                ex, ey = x + dx * STUB, y + dy * STUB
                out.append(f'(wire (pts (xy {x:.2f} {y:.2f}) (xy {ex:.2f} {ey:.2f})) (stroke (width 0) (type default)) (uuid "{u()}"))')
                out.append(f'(label "{nets[n]}" (at {ex:.2f} {ey:.2f} {la}) {eff(justify=lj)} (uuid "{u()}"))')
        if set(nets) - used:
            sys.exit(f"{ref}: table names pins the symbol lacks: {sorted(set(nets) - used)}")
    for (x, y), text in t.get("NOTES", []):
        s = text.replace('"', "'").replace("\n", "\\n")
        out.append(f'(text "{s}" (exclude_from_sim no) (at {x:.2f} {y:.2f} 0) {eff(justify="left top", size=1.6)} (uuid "{u()}"))')
    out += ['(sheet_instances (path "/" (page "1")))', "(embedded_fonts no))"]
    return "\n".join(out) + "\n"


def compare(t, netlist):
    want = {(r, p): n for r, _, _, _, _, nets, *_ in t["PARTS"] if not r.startswith("#")
            for p, n in nets.items() if n}
    got, members = {}, {}
    for net in ET.parse(netlist).getroot().find("nets"):
        name = net.get("name").lstrip("/")
        for node in net.findall("node"):
            got[(node.get("ref"), node.get("pin"))] = name
            members.setdefault(name, []).append(f"{node.get('ref')}.{node.get('pin')}")
    fails = [f"{r}.{p}: want {n}, got {got.get((r, p))}" for (r, p), n in want.items() if got.get((r, p)) != n]
    fails += [f"{r}.{p} on {n}, not in the table" for (r, p), n in got.items()
              if (r, p) not in want and not n.startswith("unconnected")]
    fails += [f"one-pin net {n}: {m}" for n, m in members.items() if len(m) < 2 and not n.startswith("unconnected")]
    return len(want), len(members), fails


def cli(*args):
    r = subprocess.run([KICAD_CLI, *args], capture_output=True, text=True)
    return r.returncode, "\n".join(l for l in (r.stdout + r.stderr).splitlines() if "Fontconfig" not in l)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    pro, table = sys.argv[1], sys.argv[2]
    p = json.load(open(pro))
    root, name = p["sheets"][0][0], os.path.splitext(os.path.basename(pro))[0]
    d = os.path.dirname(os.path.abspath(pro))
    sch = os.path.join(d, f"{name}.kicad_sch")
    libpins.use_project(d)
    t = runpy.run_path(table)
    refuse_write(Path(sch))
    if os.path.exists(sch):
        old = open(sch).read()
        if "(symbol (lib_id" in old.replace("\n", " ").replace("\t", "") or "(lib_id " in old:
            if MARKER not in old:
                sys.exit(f"refusing to overwrite {sch}: it has symbols that draft_sch.py did not write. "
                         "Once a sheet is drawn by hand, the .kicad_sch is the source.")
    open(sch, "w").write(build(t, name, root))
    print(f"wrote {sch}: {sum(1 for r in t['PARTS'] if not r[0].startswith('#'))} parts")
    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        rc, msg = cli("sch", "erc", "--severity-all", "--exit-code-violations", "-o", f"{tmp}/erc.rpt", sch)
        print("ERC:", next((l for l in msg.splitlines() if "Found" in l), msg))
        if rc:
            ok = False
            print(open(f"{tmp}/erc.rpt").read())
        rc, msg = cli("sch", "export", "netlist", "--format", "kicadxml", "-o", f"{tmp}/n.xml", sch)
        if rc or "annotation errors" in msg:
            sys.exit(f"netlist export failed:\n{msg}")
        npins, nnets, fails = compare(t, f"{tmp}/n.xml")
        for f in fails:
            print("FAIL", f)
        print(f"netlist vs table: {npins} pins, {nnets} nets, {len(fails)} problems")
        ok = ok and not fails
    os.makedirs(os.path.join(d, "docs"), exist_ok=True)
    pdf = os.path.join(d, "docs", f"{name}-schematic.pdf")
    rc, msg = cli("sch", "export", "pdf", "-o", pdf, sch)
    print("PDF:", pdf if not rc else msg)
    sys.exit(0 if ok and not rc else 1)


if __name__ == "__main__":
    main()
